from uuid import UUID
from sqlalchemy.ext.asyncio import AsyncSession

from app.repositories.user.user_repository import UserRepo
from app.core.security.password import password_hash

from app.schemas.user import UserCreate, UserUpdate
from app.models.core.user import User

from app.exceptions import InvalidCredentialsError, UserAlreadyExistsError


class UserService:
    def __init__(self, session: AsyncSession):
        self.user_repo = UserRepo(session)
        self.password_hasher = password_hash

    async def create_user(self, payload: UserCreate) -> User:
        existed_user = await self.user_repo.get_by_email(payload.email)

        if existed_user is not None:
            raise UserAlreadyExistsError(email=payload.email)

        hashed_password = self.password_hasher.hash(payload.password)

        user = User(
            username=payload.username,
            email=payload.email,
            hashed_password=hashed_password,
        )

        await self.user_repo.create(user)

        return user

    async def update_profile(self, user_id: UUID, payload: UserUpdate) -> User:
        user = await self.user_repo.get_by_id(user_id)
        if user is None:
            raise InvalidCredentialsError()

        changes = payload.model_dump(exclude_unset=True)
        if not changes:
            return user

        if "username" in changes and changes["username"] != user.username:
            existing = await self.user_repo.get_by_username(changes["username"])
            if existing is not None:
                raise UserAlreadyExistsError(username=changes["username"])

        email_changed = "email" in changes and str(changes["email"]) != user.email
        if email_changed:
            email = str(changes["email"])
            existing = await self.user_repo.get_by_email(email)
            if existing is not None:
                raise UserAlreadyExistsError(email=email)
            changes["email"] = email
            changes["is_verified"] = False
            changes["email_verified_at"] = None

        try:
            updated_user = await self.user_repo.update(user, changes)
            await self.user_repo.session.commit()
            # `updated_at` is generated by the database and can be expired
            # after the UPDATE; refresh it while still in async ORM context
            # before FastAPI serializes the response model.
            await self.user_repo.session.refresh(updated_user)
            return updated_user
        except Exception:
            await self.user_repo.session.rollback()
            raise

    async def change_password(self, user_id: UUID, current_password: str, new_password: str) -> None:
        user = await self.user_repo.get_by_id(user_id)
        if user is None or not self.password_hasher.verify(current_password, user.hashed_password):
            raise InvalidCredentialsError()

        user.hashed_password = self.password_hasher.hash(new_password)
        try:
            await self.user_repo.session.flush()
            await self.user_repo.session.commit()
        except Exception:
            await self.user_repo.session.rollback()
            raise
